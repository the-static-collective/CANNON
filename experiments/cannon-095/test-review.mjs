import test,{before} from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {pathToFileURL} from 'node:url';
import {join} from 'node:path';
import {review,verifyImageGap,verifyGit,independentFixtures,sha,HOLD,
 GRAFT_COMMIT,MOTIF_IMAGE_COMMIT,GRAFT_PINS,MOTIF_PINS} from './review.mjs';
const graft=process.env.GRAFT_SOURCE,motif=process.env.MOTIF_IMAGE_SOURCE,
 start=process.env.START_PNG,goal=process.env.TARGET_PNG,gapPath=process.env.IMAGE_GAP;
assert.ok(graft&&motif&&start&&goal&&gapPath,'Exact owner/checkouts and actual PNGs required');
let packet,gap,graftCode;
before(async()=>{
 gap=JSON.parse(readFileSync(gapPath,'utf8'));
 packet=await review(graft,motif,start,goal,gap);
 graftCode=await import(pathToFileURL(join(graft,'src/visual-grammar-030.mjs')).href);
});
test('read real PNG bytes from exact source-pinned MOTIF-006 image-in instrument',()=>{
 assert.equal(verifyImageGap(motif,start,goal,gap),gap.content_sha256);
 assert.equal(packet.source_motif_image_in.commit,MOTIF_IMAGE_COMMIT);
 assert.equal(packet.original_png_evidence.start_sha256,sha(readFileSync(start)));
 assert.equal(packet.original_png_evidence.target_sha256,sha(readFileSync(goal)));
});
test('source-owning GRAFT-030 is unmerged independent exact Git code',()=>{
 assert.equal(packet.source_graft.commit,GRAFT_COMMIT);
 assert.deepEqual(verifyGit(graft,GRAFT_COMMIT,GRAFT_PINS),
  packet.source_graft.exact_git_blobs);
 assert.deepEqual(verifyGit(motif,MOTIF_IMAGE_COMMIT,MOTIF_PINS),
  packet.source_motif_image_in.exact_git_blobs);
});
test('new visual executable was generated by original GRAFT-030',()=>{
 const x=packet.source_owned_generated;
 const fromOriginal=graftCode.compileVariant(gap,x.mode);
 assert.equal(x.mode,'move');
 assert.equal(x.source,fromOriginal.source);
 assert.equal(x.source_sha256,fromOriginal.source_sha256);
 assert.equal(x.code_installed,false);
 assert.equal(x.right_to_contact_apis,false);
});
test('three distinct visual grammar modes considered and rejected alternatives',()=>{
 assert.equal(packet.native_test_counts.generated_candidates,3);
 assert.equal(packet.native_test_counts.rejected_variants,2);
 assert.ok(packet.native_test_counts.selection>=3);
 assert.ok(packet.native_test_counts.negative>=3);
});
test('eight independently constructed synthetic visual observations all pass',()=>{
 assert.equal(packet.independent_final.correct,8);
 assert.equal(packet.independent_final.n,8);
 assert.equal(packet.independent_final.results.filter(x=>x.status==='PROPOSED_FRAME').length,5);
 assert.equal(packet.independent_final.results.filter(x=>x.status!=='PROPOSED_FRAME').length,3);
 assert.ok(packet.independent_final.never_used_to_select_source);
});
test('generated JavaScript makes physical frame predictions not source writes',async()=>{
 const {execute}=await import('data:text/javascript;base64,'+
  Buffer.from(packet.source_owned_generated.source).toString('base64'));
 const example=independentFixtures(graftCode)[0];
 const out=execute(example);
 assert.equal(out.status,'PROPOSED_FRAME');
 assert.notDeepEqual(out.frame,example.rows);
 assert.equal(out.frame.flatMap(r=>[...r]).filter(c=>c==='R').length,4);
});
test('classical same-budget raster translation ties: no invented advantage',()=>{
 assert.equal(packet.fair_classical.correct,8);
 assert.equal(packet.fair_classical.superior_to_classical,false);
 assert.equal(packet.fair_classical.fixed_add_only_cannot_delete_old_red_pixels,true);
});
test('no abstract photo semantics, authority, deployment or live inference',()=>{
 assert.equal(packet.original_png_evidence.visual_semantics,'THREE_COLOR_GRID_ONLY');
 assert.equal(packet.original_png_evidence.image_uploads_to_remote_ai,0);
 assert.equal(packet.authority.signed,false);
 assert.equal(packet.authority.operator_admitted,false);
 assert.equal(packet.authority.external_actions,0);
 assert.equal(packet.authority.contacts,0);
 assert.equal(packet.authority.repository_writes,0);
});
test('visual code receipt integrity is deterministic',()=>{
 const {content_sha256,...body}=packet;
 assert.equal(sha(body),content_sha256);
});
test('wrong source root is never treated as verified owner',()=>{
 assert.throws(()=>verifyGit(process.cwd(),GRAFT_COMMIT,GRAFT_PINS),HOLD);
});
test('source-image substitution fails independent bytes',()=>{
 const wrong=Buffer.from(readFileSync(start));wrong[wrong.length-4]^=1;
 assert.notEqual(sha(wrong),gap.start_png_sha256);
});
test('undocumented new source tokens cannot execute in exact native GRAFT grammar',()=>{
 assert.throws(()=>graftCode.compileVariant(gap,'eval'),HOLD);
});
